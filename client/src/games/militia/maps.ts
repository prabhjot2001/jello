export type Rect = [x: number, y: number, w: number, h: number];

export interface MilitiaMapDef {
  id: string;
  w: number;
  h: number;
  /** 1 = normal gravity */
  gravity: number;
  solids: Rect[];
  /** player centre positions */
  spawns: [number, number][];
  /** crate centres, in the same order as MILITIA_MAPS[].crates on the server */
  crates: [number, number][];
  sky: [string, string];
  solid: string;
  edge: string;
  decor: "city" | "roofs" | "cave" | "space";
}

const frame = (w: number, h: number, floor = 100): Rect[] => [
  [0, h - floor, w, floor],
  [0, 0, 36, h],
  [w - 36, 0, 36, h],
];

